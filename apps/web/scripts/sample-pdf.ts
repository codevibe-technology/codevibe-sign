import { writeFileSync } from 'node:fs';
import { PDFDocument, StandardFonts, rgb } from 'pdf-lib';
import { SAMPLE_FIELDS, SAMPLE_PAGE } from '../src/lib/sample-envelope';

// Writes the first-run sample agreement as base64 into src/server/sample/agreement-pdf.ts.
// Run `pnpm --filter web sample:pdf` after changing the text or the field boxes.

const ink = rgb(0.05, 0.11, 0.16);
const muted = rgb(0.32, 0.38, 0.47);
const line = rgb(0.72, 0.77, 0.83);

const doc = await PDFDocument.create();
doc.setTitle('Sample agreement');
doc.setAuthor('Codevibe Sign');
doc.setCreator('Codevibe Sign');
doc.setProducer('Codevibe Sign');
doc.setCreationDate(new Date('2026-11-01T00:00:00Z'));
doc.setModificationDate(new Date('2026-11-01T00:00:00Z'));
const page = doc.addPage([SAMPLE_PAGE.width, SAMPLE_PAGE.height]);
const regular = await doc.embedFont(StandardFonts.Helvetica);
const bold = await doc.embedFont(StandardFonts.HelveticaBold);
const top = (y: number) => SAMPLE_PAGE.height - y;

page.drawRectangle({
  x: 0,
  y: top(8),
  width: SAMPLE_PAGE.width,
  height: 8,
  color: rgb(0.18, 0.83, 0.75),
});
page.drawText('CODEVIBE SIGN', { x: 64, y: top(64), size: 10, font: bold, color: muted });
page.drawText('Sample agreement', { x: 64, y: top(100), size: 26, font: bold, color: ink });
page.drawText('A practice document. Signing it has no legal effect.', {
  x: 64,
  y: top(126),
  size: 12,
  font: regular,
  color: muted,
});

const paragraphs = [
  [
    '1. What this is',
    'This page was added to your new workspace so you can see the whole signing flow on a document of your own before you send a real one.',
  ],
  [
    '2. What happens when you send it',
    'You receive an email with a signing link. The link opens the signing page in your browser. No account or app is needed by the person who signs.',
  ],
  [
    '3. What you get back',
    'Once you sign, the PDF is sealed with the workspace certificate and a signing certificate is added: who signed, when, from where, and a fingerprint of every page.',
  ],
  [
    '4. Checking it later',
    'Upload the sealed copy on the Verify page at any time. It confirms the document has not changed since it was sealed.',
  ],
] as const;

let y = 176;
const width = SAMPLE_PAGE.width - 128;
for (const [heading, body] of paragraphs) {
  page.drawText(heading, { x: 64, y: top(y), size: 13, font: bold, color: ink });
  y += 20;
  const words = body.split(' ');
  let current = '';
  for (const word of words) {
    const next = current ? `${current} ${word}` : word;
    if (regular.widthOfTextAtSize(next, 11) > width) {
      page.drawText(current, { x: 64, y: top(y), size: 11, font: regular, color: ink });
      y += 16;
      current = word;
    } else {
      current = next;
    }
  }
  page.drawText(current, { x: 64, y: top(y), size: 11, font: regular, color: ink });
  y += 34;
}

for (const field of SAMPLE_FIELDS) {
  const { x, y: fy, width: w, height: h } = field.rect;
  page.drawLine({
    start: { x, y: top(fy + h) },
    end: { x: x + w, y: top(fy + h) },
    thickness: 1,
    color: line,
  });
  page.drawText(field.caption, { x, y: top(fy + h + 16), size: 10, font: regular, color: muted });
}

page.drawText('Made with Codevibe Sign  |  sign.codevibe.in', {
  x: 64,
  y: 48,
  size: 9,
  font: regular,
  color: muted,
});

const bytes = await doc.save({ useObjectStreams: true });
const base64 = Buffer.from(bytes).toString('base64');
writeFileSync(
  new URL('../src/server/sample/agreement-pdf.ts', import.meta.url),
  `// Generated by scripts/sample-pdf.ts; do not edit by hand.\nexport const SAMPLE_AGREEMENT_PDF =\n  '${base64}';\n`,
);
console.log(`Wrote the sample agreement: ${bytes.length} bytes.`);
